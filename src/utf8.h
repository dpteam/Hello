/*
 * utf8.h — минимальный, но корректный UTF-8 для Codename Hello.
 *
 * Никаких зависимостей: только стандартная библиотека C11.
 * Все функции работают с NUL-терминированными строками, но
 * декодер умеет и с явной длиной (для битых данных).
 */
#ifndef HELLO_UTF8_H
#define HELLO_UTF8_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* Сколько байт занимает кодпоинт по его первому байту.
 * 0 — байт не может начинать последовательность. */
int utf8_sequence_length(unsigned char lead);

/* Декодирует один кодпоинт.
 * Возвращает число прочитанных байт (1..4), 0 — конец строки,
 * -1 — некорректная последовательность (потребитель обычно
 * пропускает один байт и пробует снова). */
int utf8_decode(const char *s, size_t len, uint32_t *out);

/* Кодирует кодпоинт. Возвращает число записанных байт (1..4).
 * Для суррогатов и значений > 0x10FFFF возвращает -1 и ничего
 * не пишет. out должен вмещать минимум 4 байта. */
int utf8_encode(uint32_t cp, char out[4]);

/* Длина строки в символах (не в байтах). Битые байты считаются
 * за один символ — так интерфейс не «съедает» ввод пользователя. */
size_t utf8_strlen(const char *s);

/* Проверка, что строка целиком корректна. */
bool utf8_valid(const char *s);

/* Начало предыдущего символа перед байтовым смещением pos. */
size_t utf8_prev(const char *s, size_t pos);

/* Начало следующего символа после байтового смещения pos. */
size_t utf8_next(const char *s, size_t pos);

/* Наибольшая длина <= max_bytes, оканчивающаяся на границе символа. */
size_t utf8_clip(const char *s, size_t max_bytes);

/* Приведение к нижнему регистру для ASCII, кириллицы и латиницы
 * с диакритикой (достаточно для сравнения фраз). */
uint32_t utf8_casefold(uint32_t cp);

/* Является ли кодпоинт «шумом»: пробел, пунктуация, управляющий. */
bool utf8_is_noise(uint32_t cp);

/* Копия строки в куче (NULL при нехватке памяти). */
char *utf8_dup(const char *s);
char *utf8_dup_range(const char *s, size_t n);

/* Дописывает n байт в растущий буфер.
 * buf/cap/len — состояние буфера; buf может быть NULL при cap == 0.
 * Возвращает false только при нехватке памяти. */
bool utf8_buf_append(char **buf, size_t *len, size_t *cap,
                     const char *text, size_t n);

#endif /* HELLO_UTF8_H */
